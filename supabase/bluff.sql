-- Bluff Quiz. Apply after reliability_upgrade.sql (shared code lookup/rate limit).
-- All questions, snapshots, tokens, bluffs and votes remain in the private schema.
create schema if not exists private;
create table if not exists private.bluff_questions(
 id bigint generated by default as identity primary key,
 owner_id uuid references auth.users(id) on delete cascade,
 seed_key text unique,
 question text not null check(length(btrim(question)) between 5 and 500),
 correct_answer text not null check(length(btrim(correct_answer)) between 1 and 180),
 category text not null default '' check(length(category)<=80),
 source_url text not null default '' check(length(source_url)<=1000),
 updated_at timestamptz not null default now(),
 check(owner_id is not null or seed_key is not null)
);
create index if not exists bluff_questions_owner_idx on private.bluff_questions(owner_id,id);
create table if not exists private.bluff_sessions(
 id uuid primary key default gen_random_uuid(),owner_id uuid not null references auth.users(id) on delete cascade,
 join_code text unique not null,
 phase text not null default 'lobby' check(phase in ('lobby','question','bluff','vote','reveal','leaderboard','ended')),
 round_index integer not null default 0,round_count integer not null check(round_count between 1 and 50),
 deadline timestamptz,revision bigint not null default 1,
 created_at timestamptz not null default now(),updated_at timestamptz not null default now()
);
create index if not exists bluff_sessions_owner_idx on private.bluff_sessions(owner_id,created_at desc);
create table if not exists private.bluff_rounds(
 session_id uuid references private.bluff_sessions(id) on delete cascade,round_index integer not null,
 question text not null,correct_answer text not null,category text not null,source_url text not null,
 reveal_count integer not null default 0,scored_at timestamptz,
 primary key(session_id,round_index)
);
create table if not exists private.bluff_players(
 id uuid primary key default gen_random_uuid(),session_id uuid not null references private.bluff_sessions(id) on delete cascade,
 name text not null check(length(btrim(name)) between 1 and 40),token_hash text not null,
 score integer not null default 0,joined_at timestamptz not null default now()
);
create unique index if not exists bluff_players_name_idx on private.bluff_players(session_id,lower(btrim(name)));
create table if not exists private.bluff_entries(
 session_id uuid,round_index integer,player_id uuid references private.bluff_players(id) on delete cascade,
 answer text not null check(length(btrim(answer)) between 1 and 180),submitted_at timestamptz not null default now(),
 primary key(session_id,round_index,player_id),foreign key(session_id,round_index) references private.bluff_rounds on delete cascade
);
create table if not exists private.bluff_options(
 id uuid primary key default gen_random_uuid(),session_id uuid,round_index integer,
 answer text not null,is_truth boolean not null default false,author_ids uuid[] not null default '{}',position integer not null,
 foreign key(session_id,round_index) references private.bluff_rounds on delete cascade,
 unique(session_id,round_index,position)
);
create unique index if not exists bluff_one_truth_idx on private.bluff_options(session_id,round_index) where is_truth;
create table if not exists private.bluff_votes(
 session_id uuid,round_index integer,player_id uuid references private.bluff_players(id) on delete cascade,
 option_id uuid not null references private.bluff_options(id) on delete cascade,
 primary key(session_id,round_index,player_id),foreign key(session_id,round_index) references private.bluff_rounds on delete cascade
);
create index if not exists bluff_entries_player_idx on private.bluff_entries(player_id);
create index if not exists bluff_votes_player_idx on private.bluff_votes(player_id);
create index if not exists bluff_votes_option_idx on private.bluff_votes(option_id);
-- Realtime carries only a random room UUID and revision; no gameplay content.
create table if not exists public.bluff_live_signals(
 session_id uuid primary key references private.bluff_sessions(id) on delete cascade,revision bigint not null
);
alter table public.bluff_live_signals enable row level security;
drop policy if exists bluff_signal_read on public.bluff_live_signals;
create policy bluff_signal_read on public.bluff_live_signals for select to anon,authenticated using(true);
revoke all on public.bluff_live_signals from public,anon,authenticated;
grant select on public.bluff_live_signals to anon,authenticated;
do $$declare t text;begin
 foreach t in array array['bluff_questions','bluff_sessions','bluff_rounds','bluff_players','bluff_entries','bluff_options','bluff_votes'] loop
 execute format('alter table private.%I enable row level security',t);
 execute format('revoke all on private.%I from public,anon,authenticated',t);
 end loop;
 if exists(select 1 from pg_publication where pubname='supabase_realtime') and not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='bluff_live_signals') then
 alter publication supabase_realtime add table public.bluff_live_signals;
 end if;
end;$$;

create or replace function private.bluff_normalize(p_text text)
returns text language sql immutable set search_path='' as $$select lower(regexp_replace(btrim(coalesce(p_text,'')),'[[:space:][:punct:]]+','','g'));$$;
create or replace function private.bluff_token_valid(p_session uuid,p_player uuid,p_token text)
returns boolean language sql stable security definer set search_path='' as $$
 select coalesce(p_token ~ '^[a-f0-9]{64}$',false) and exists(select 1 from private.bluff_players where id=p_player and session_id=p_session and token_hash=encode(sha256(convert_to(p_token,'UTF8')),'hex'));
$$;
create or replace function private.bluff_touch(p_session uuid)
returns void language plpgsql security definer set search_path='' as $$
declare v bigint;begin
 update private.bluff_sessions set revision=revision+1,updated_at=clock_timestamp() where id=p_session returning revision into v;
 insert into public.bluff_live_signals(session_id,revision) values(p_session,v) on conflict(session_id) do update set revision=excluded.revision;
end;$$;

create or replace function public.bluff_question_list()
returns jsonb language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null then return jsonb_build_object('ok',false,'error','NOT_AUTHENTICATED');end if;
 return jsonb_build_object('ok',true,'questions',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'question',question,'correct_answer',correct_answer,'category',category,'source_url',source_url,'editable',owner_id=auth.uid()) order by id),'[]') from private.bluff_questions where owner_id=auth.uid() or owner_id is null));
end;$$;
create or replace function public.bluff_question_save(p_id bigint,p_question text,p_correct_answer text,p_category text,p_source_url text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare qid bigint;begin
 if auth.uid() is null then return jsonb_build_object('ok',false,'error','NOT_AUTHENTICATED');end if;
 if p_question is null or length(btrim(p_question)) not between 5 and 500 or p_correct_answer is null or length(btrim(p_correct_answer)) not between 1 and 180 or length(coalesce(p_category,''))>80 or length(coalesce(p_source_url,''))>1000 or (coalesce(p_source_url,'')<>'' and p_source_url !~ '^https://[^[:space:]]+$') then return jsonb_build_object('ok',false,'error','INVALID_QUESTION');end if;
 if p_id is null then
 insert into private.bluff_questions(owner_id,question,correct_answer,category,source_url) values(auth.uid(),btrim(p_question),btrim(p_correct_answer),coalesce(p_category,''),coalesce(p_source_url,'')) returning id into qid;
 else
 update private.bluff_questions set question=btrim(p_question),correct_answer=btrim(p_correct_answer),category=coalesce(p_category,''),source_url=coalesce(p_source_url,''),updated_at=now() where id=p_id and owner_id=auth.uid() returning id into qid;
 if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 end if;
 return jsonb_build_object('ok',true,'id',qid);
end;$$;
create or replace function public.bluff_question_delete(p_id bigint)
returns jsonb language plpgsql security definer set search_path='' as $$
begin
 if auth.uid() is null then return jsonb_build_object('ok',false,'error','NOT_AUTHENTICATED');end if;
 delete from private.bluff_questions where id=p_id and owner_id=auth.uid();
 if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 return jsonb_build_object('ok',true);
end;$$;

create or replace function public.bluff_create(p_round_count integer,p_question_ids bigint[] default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare sid uuid;code text;ids bigint[];begin
 if auth.uid() is null then return jsonb_build_object('ok',false,'error','NOT_AUTHENTICATED');end if;
 if p_round_count is null or p_round_count not between 1 and 50 then return jsonb_build_object('ok',false,'error','INVALID_ROUND_COUNT');end if;
 if p_question_ids is not null then
 if cardinality(p_question_ids)<>p_round_count or cardinality(p_question_ids)<>(select count(distinct x) from unnest(p_question_ids) x) or exists(select 1 from unnest(p_question_ids) x where not exists(select 1 from private.bluff_questions where id=x and (owner_id=auth.uid() or owner_id is null))) then return jsonb_build_object('ok',false,'error','INVALID_SELECTION');end if;
 if (select count(distinct private.bluff_normalize(question)) from private.bluff_questions where id=any(p_question_ids))<>p_round_count then return jsonb_build_object('ok',false,'error','INVALID_SELECTION');end if;
 ids:=p_question_ids;
 else
 select array_agg(id) into ids from (select id from (
 select distinct on (private.bluff_normalize(question)) id from private.bluff_questions
 where owner_id=auth.uid() or owner_id is null
 order by private.bluff_normalize(question),(owner_id is not null) desc,id desc
 ) unique_questions order by random() limit p_round_count) q;
 if coalesce(cardinality(ids),0)<>p_round_count then return jsonb_build_object('ok',false,'error','NOT_ENOUGH_QUESTIONS');end if;
 end if;
 for attempt in 1..30 loop
 code:='';for pos in 1..5 loop code:=code||substr('ABCDEFGHJKLMNPQRSTUVWXYZ23456789',1+floor(random()*32)::int,1);end loop;
 begin
 insert into private.bluff_sessions(owner_id,join_code,round_count) values(auth.uid(),code,p_round_count) returning id into sid;exit;
 exception when unique_violation then sid:=null;end;
 end loop;
 if sid is null then return jsonb_build_object('ok',false,'error','CODE_GENERATION_FAILED');end if;
 insert into private.bluff_rounds(session_id,round_index,question,correct_answer,category,source_url)
 select sid,(i.n-1)::integer,q.question,q.correct_answer,q.category,q.source_url from unnest(ids) with ordinality i(id,n) join private.bluff_questions q on q.id=i.id;
 perform private.bluff_touch(sid);
 return jsonb_build_object('ok',true,'session_id',sid,'join_code',code);
end;$$;
create or replace function public.bluff_join(p_code text,p_name text,p_token text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s private.bluff_sessions%rowtype;p private.bluff_players%rowtype;v_name text:=btrim(coalesce(p_name,''));begin
 if not private.classroom_join_allowed('bluff') then return jsonb_build_object('ok',false,'error','JOIN_RATE_LIMITED');end if;
 if upper(btrim(coalesce(p_code,''))) !~ '^[A-Z0-9]{5}$' or length(v_name) not between 1 and 40 or p_token is null or p_token !~ '^[a-f0-9]{64}$' then return jsonb_build_object('ok',false,'error','INVALID_JOIN_INPUT');end if;
 select * into s from private.bluff_sessions where join_code=upper(btrim(p_code)) and phase<>'ended' for update;
 if not found then return jsonb_build_object('ok',false,'error','SESSION_NOT_FOUND');end if;
 select * into p from private.bluff_players where session_id=s.id and lower(btrim(name))=lower(v_name);
 if found then
 if not private.bluff_token_valid(s.id,p.id,p_token) then return jsonb_build_object('ok',false,'error','NAME_TAKEN');end if;
 else
 if s.phase<>'lobby' then return jsonb_build_object('ok',false,'error','GAME_ALREADY_STARTED');end if;
 if (select count(*) from private.bluff_players where session_id=s.id)>=50 then return jsonb_build_object('ok',false,'error','ROOM_FULL');end if;
 insert into private.bluff_players(session_id,name,token_hash) values(s.id,v_name,encode(sha256(convert_to(p_token,'UTF8')),'hex')) returning * into p;
 perform private.bluff_touch(s.id);
 end if;
 return jsonb_build_object('ok',true,'session_id',s.id,'player_id',p.id,'name',p.name,'join_code',s.join_code);
end;$$;

-- One authoritative state serializer; no caller can request host fields through a flag.
create or replace function private.bluff_state(p_session uuid,p_player uuid,p_host boolean)
returns jsonb language plpgsql stable security definer set search_path='' as $$
declare s private.bluff_sessions%rowtype;r private.bluff_rounds%rowtype;players jsonb;opts jsonb;entries jsonb;own jsonb;voted uuid;begin
 select * into s from private.bluff_sessions where id=p_session;
 if not found then return jsonb_build_object('ok',false,'error','SESSION_NOT_FOUND');end if;
 select * into r from private.bluff_rounds where session_id=s.id and round_index=s.round_index;
 select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'name',p.name,'score',p.score,'submitted',exists(select 1 from private.bluff_entries e where e.session_id=s.id and e.round_index=s.round_index and e.player_id=p.id),'voted',exists(select 1 from private.bluff_votes v where v.session_id=s.id and v.round_index=s.round_index and v.player_id=p.id)) order by p.score desc,lower(p.name),p.id),'[]') into players from private.bluff_players p where p.session_id=s.id;
 if s.phase in ('vote','reveal','leaderboard','ended') then
 select coalesce(jsonb_agg(jsonb_build_object('id',o.id,'answer',o.answer,'own',coalesce(p_player=any(o.author_ids),false),'revealed',o.position<r.reveal_count)||case when o.position<r.reveal_count then jsonb_build_object('is_truth',o.is_truth,'authors',(select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'name',p.name) order by p.name),'[]') from private.bluff_players p where p.id=any(o.author_ids)),'voters',(select coalesce(jsonb_agg(jsonb_build_object('id',p.id,'name',p.name) order by p.name),'[]') from private.bluff_votes v join private.bluff_players p on p.id=v.player_id where v.option_id=o.id)) else '{}'::jsonb end order by o.position),'[]') into opts from private.bluff_options o where o.session_id=s.id and o.round_index=s.round_index;
 end if;
 if p_host and s.phase in ('bluff','reveal','leaderboard','ended') then
 select coalesce(jsonb_agg(jsonb_build_object('player',p.name,'answer',e.answer) order by e.submitted_at),'[]') into entries from private.bluff_entries e join private.bluff_players p on p.id=e.player_id where e.session_id=s.id and e.round_index=s.round_index;
 end if;
 select jsonb_build_object('answer',answer) into own from private.bluff_entries where session_id=s.id and round_index=s.round_index and player_id=p_player;
 select option_id into voted from private.bluff_votes where session_id=s.id and round_index=s.round_index and player_id=p_player;
 return jsonb_build_object('ok',true,'session_id',s.id,'join_code',s.join_code,'phase',s.phase,'round_index',s.round_index,'round_count',s.round_count,'revision',s.revision,'deadline',s.deadline,'server_now',clock_timestamp(),'reveal_count',r.reveal_count,'question',case when s.phase='lobby' then null else r.question end,'category',case when s.phase='lobby' then null else r.category end,'source_url',case when s.phase in ('leaderboard','ended') then r.source_url else null end,'correct_answer',case when s.phase='leaderboard' then r.correct_answer else null end,'players',players,'options',coalesce(opts,'[]'),'entries',coalesce(entries,'[]'),'own_entry',own,'own_vote',voted);
end;$$;
create or replace function public.bluff_host_state(p_session_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$begin
 if not exists(select 1 from private.bluff_sessions where id=p_session_id and owner_id=auth.uid()) then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 return private.bluff_state(p_session_id,null,true);end;$$;
create or replace function public.bluff_player_state(p_session_id uuid,p_player_id uuid,p_token text)
returns jsonb language plpgsql security definer set search_path='' as $$begin
 if not private.bluff_token_valid(p_session_id,p_player_id,p_token) then return jsonb_build_object('ok',false,'error','INVALID_PARTICIPANT_TOKEN');end if;
 return private.bluff_state(p_session_id,p_player_id,false);end;$$;

create or replace function public.bluff_submit(p_session_id uuid,p_player_id uuid,p_token text,p_round integer,p_answer text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s private.bluff_sessions%rowtype;truth text;begin
 if not private.bluff_token_valid(p_session_id,p_player_id,p_token) then return jsonb_build_object('ok',false,'error','INVALID_PARTICIPANT_TOKEN');end if;
 select * into s from private.bluff_sessions where id=p_session_id for update;
 if p_round is null or p_round<>s.round_index or s.phase<>'bluff' then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
 if s.deadline is not null and clock_timestamp()>=s.deadline then return jsonb_build_object('ok',false,'error','TIME_EXPIRED');end if;
 if p_answer is null or length(btrim(p_answer)) not between 1 and 180 or private.bluff_normalize(p_answer)='' then return jsonb_build_object('ok',false,'error','INVALID_ANSWER');end if;
 select correct_answer into truth from private.bluff_rounds where session_id=s.id and round_index=s.round_index;
 if private.bluff_normalize(p_answer)=private.bluff_normalize(truth) then return jsonb_build_object('ok',false,'error','ANSWER_MATCHES_TRUTH');end if;
 insert into private.bluff_entries(session_id,round_index,player_id,answer) values(s.id,s.round_index,p_player_id,btrim(p_answer)) on conflict(session_id,round_index,player_id) do update set answer=excluded.answer,submitted_at=clock_timestamp();
 perform private.bluff_touch(s.id);return jsonb_build_object('ok',true);
end;$$;
create or replace function public.bluff_vote(p_session_id uuid,p_player_id uuid,p_token text,p_round integer,p_option_id uuid)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s private.bluff_sessions%rowtype;o private.bluff_options%rowtype;prev uuid;begin
 if not private.bluff_token_valid(p_session_id,p_player_id,p_token) then return jsonb_build_object('ok',false,'error','INVALID_PARTICIPANT_TOKEN');end if;
 select * into s from private.bluff_sessions where id=p_session_id for update;
 if p_round is null or p_round<>s.round_index or s.phase<>'vote' then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
 if s.deadline is not null and clock_timestamp()>=s.deadline then return jsonb_build_object('ok',false,'error','TIME_EXPIRED');end if;
 select * into o from private.bluff_options where id=p_option_id and session_id=s.id and round_index=s.round_index;
 if not found then return jsonb_build_object('ok',false,'error','INVALID_OPTION');end if;
 if p_player_id=any(o.author_ids) then return jsonb_build_object('ok',false,'error','OWN_VOTE_FORBIDDEN');end if;
 select option_id into prev from private.bluff_votes where session_id=s.id and round_index=s.round_index and player_id=p_player_id;
 if found then return jsonb_build_object('ok',prev=p_option_id,'error',case when prev=p_option_id then null else 'VOTE_ALREADY_CAST' end);end if;
 insert into private.bluff_votes(session_id,round_index,player_id,option_id) values(s.id,s.round_index,p_player_id,o.id);
 perform private.bluff_touch(s.id);return jsonb_build_object('ok',true);
end;$$;

create or replace function public.bluff_host_action(p_session_id uuid,p_round integer,p_phase text,p_action text,p_seconds integer default null,p_reveal_count integer default null)
returns jsonb language plpgsql security definer set search_path='' as $$
declare s private.bluff_sessions%rowtype;r private.bluff_rounds%rowtype;n integer;act text:=p_action;begin
 select * into s from private.bluff_sessions where id=p_session_id for update;
 if not found or s.owner_id is distinct from auth.uid() then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 if act='end' then
 if s.phase<>'ended' then update private.bluff_sessions set phase='ended',deadline=null where id=s.id;perform private.bluff_touch(s.id);end if;
 return jsonb_build_object('ok',true);end if;
 if p_round is null or p_phase is null or p_round<>s.round_index or p_phase<>s.phase then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
 select * into r from private.bluff_rounds where session_id=s.id and round_index=s.round_index for update;
 if act='expire' then
 if s.deadline is null or clock_timestamp()<s.deadline then return jsonb_build_object('ok',true);end if;
 act:=case s.phase when 'bluff' then 'open_vote' when 'vote' then 'reveal' else '' end;
 end if;
 if act='timer' and s.phase in ('bluff','vote') then
 if p_seconds is not null and p_seconds not between 5 and 600 then return jsonb_build_object('ok',false,'error','INVALID_TIMER');end if;
 update private.bluff_sessions set deadline=case when p_seconds is null then null else clock_timestamp()+make_interval(secs=>p_seconds) end where id=s.id;
 elsif act='start' and s.phase='lobby' then
 if (select count(*) from private.bluff_players where session_id=s.id)<2 then return jsonb_build_object('ok',false,'error','NEED_TWO_PLAYERS');end if;
 update private.bluff_sessions set phase='question' where id=s.id;
 elsif act='open_bluff' and s.phase='question' then
 update private.bluff_sessions set phase='bluff',deadline=null where id=s.id;
 elsif act='open_vote' and s.phase='bluff' then
 if not exists(select 1 from private.bluff_entries where session_id=s.id and round_index=s.round_index) then return jsonb_build_object('ok',false,'error','NO_BLUFFS');end if;
 insert into private.bluff_options(session_id,round_index,answer,is_truth,author_ids,position)
 select s.id,s.round_index,q.answer,q.truth,q.authors,(row_number() over(order by random())-1)::integer from (
 select r.correct_answer as answer,true as truth,'{}'::uuid[] as authors
 union all select min(e.answer),false,array_agg(e.player_id) from private.bluff_entries e where e.session_id=s.id and e.round_index=s.round_index group by private.bluff_normalize(e.answer)) q;
 update private.bluff_sessions set phase='vote',deadline=null where id=s.id;
 elsif act='reveal' and s.phase='vote' then
 update private.bluff_sessions set phase='reveal',deadline=null where id=s.id;
 elsif act='reveal_next' and s.phase='reveal' then
 if p_reveal_count is null or p_reveal_count<>r.reveal_count then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
 select count(*) into n from private.bluff_options where session_id=s.id and round_index=s.round_index;
 update private.bluff_rounds set reveal_count=reveal_count+1 where session_id=s.id and round_index=s.round_index;
 if r.reveal_count+1>=n and r.scored_at is null then
 update private.bluff_players p set score=score+coalesce((select sum(case when o.is_truth and v.player_id=p.id then 1 when not o.is_truth and p.id=any(o.author_ids) then 2 else 0 end) from private.bluff_votes v join private.bluff_options o on o.id=v.option_id where v.session_id=s.id and v.round_index=s.round_index),0)::integer where p.session_id=s.id;
 update private.bluff_rounds set scored_at=clock_timestamp() where session_id=s.id and round_index=s.round_index;
 update private.bluff_sessions set phase='leaderboard' where id=s.id;
 end if;
 elsif act='next' and s.phase='leaderboard' then
 update private.bluff_sessions set phase=case when round_index+1>=round_count then 'ended' else 'question' end,round_index=case when round_index+1>=round_count then round_index else round_index+1 end,deadline=null where id=s.id;
 else return jsonb_build_object('ok',false,'error','INVALID_ACTION');end if;
 perform private.bluff_touch(s.id);return jsonb_build_object('ok',true);
end;$$;

create or replace function public.bluff_owned_sessions()
