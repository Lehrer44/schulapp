-- Näher dran: estimation game with numeric answers. Apply after same.sql.
-- Private storage and checked APIs, following the other party games.
create table if not exists private.closer_catalogs(owner_id uuid primary key references auth.users on delete cascade);
create table if not exists private.closer_questions(
 id bigint generated by default as identity primary key,owner_id uuid not null references auth.users on delete cascade,
 question text not null check(length(btrim(question)) between 5 and 300),
 answer numeric not null check(abs(answer)<=1000000000000),
 unit text not null default '' check(length(unit)<=20)
);
create index if not exists closer_questions_owner on private.closer_questions(owner_id);
create table if not exists private.closer_quizzes(
 id uuid primary key default gen_random_uuid(),owner_id uuid not null references auth.users on delete cascade,
 name text not null check(length(btrim(name)) between 1 and 120),questions jsonb not null
);
create index if not exists closer_quizzes_owner on private.closer_quizzes(owner_id);
create table if not exists private.closer_sessions(
 id uuid primary key default gen_random_uuid(),owner_id uuid not null references auth.users on delete cascade,
 join_code text unique not null,questions jsonb not null,round_index integer not null default 0,
 phase text not null default 'lobby' check(phase in ('lobby','guess','reveal','leaderboard','ended')),
 revision bigint not null default 1,created_at timestamptz not null default now()
);
create index if not exists closer_sessions_owner on private.closer_sessions(owner_id);
create table if not exists private.closer_players(
 id uuid primary key default gen_random_uuid(),session_id uuid not null references private.closer_sessions on delete cascade,
 name text not null check(length(btrim(name)) between 1 and 40),token_hash text not null,score integer not null default 0,
 joined_at timestamptz not null default clock_timestamp(),unique(session_id,id)
);
create unique index if not exists closer_player_name on private.closer_players(session_id,lower(btrim(name)));
create table if not exists private.closer_guesses(
 session_id uuid not null,round_index integer not null,player_id uuid not null,
 value numeric not null check(abs(value)<=1000000000000),points integer,
 primary key(session_id,round_index,player_id),
 foreign key(session_id,player_id) references private.closer_players(session_id,id) on delete cascade
);
create table if not exists public.closer_live_signals(
 session_id uuid primary key references private.closer_sessions on delete cascade,revision bigint not null
);
alter table public.closer_live_signals enable row level security;
drop policy if exists closer_signal_read on public.closer_live_signals;
create policy closer_signal_read on public.closer_live_signals for select to anon,authenticated using(true);
revoke all on public.closer_live_signals from public,anon,authenticated;
grant select on public.closer_live_signals to anon,authenticated;
do $$declare t text;begin
 foreach t in array array['catalogs','questions','quizzes','sessions','players','guesses'] loop
 execute format('alter table private.%I enable row level security','closer_'||t);
 execute format('revoke all on private.%I from public,anon,authenticated','closer_'||t);
 end loop;
 if exists(select 1 from pg_publication where pubname='supabase_realtime') and not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='closer_live_signals') then
 alter publication supabase_realtime add table public.closer_live_signals;
 end if;
end;$$;

-- One private implementation keeps authentication, locking and visibility rules together.
-- The answer of the current round is only returned once the host has revealed it.
create or replace function private.closer_api(p_action text,a jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare uid uuid:=auth.uid();s private.closer_sessions%rowtype;p private.closer_players%rowtype;
 sid uuid;pid uuid;qid bigint;qs jsonb;ids bigint[];code text;txt text;v_unit text;num numeric;n integer;changed boolean:=false;v_answer numeric;
begin
 if p_action not in ('join','player_state','guess') and uid is null then return jsonb_build_object('ok',false,'error','NOT_AUTHENTICATED');end if;
 if p_action in ('question_list','question_save','question_delete','quiz_list','quiz_save','quiz_delete','quiz_start','create') then
  -- Seed once per account, so editing/deleting a starter never affects another teacher.
  insert into private.closer_catalogs values(uid) on conflict do nothing;
  if found then
   insert into private.closer_questions(owner_id,question,answer,unit) values
    (uid,'Wie hoch ist der Kölner Dom?',157,'m'),
    (uid,'Wie viele Knochen hat ein erwachsener Mensch?',206,'Knochen'),
    (uid,'Wie viele Mitgliedstaaten hat die Europäische Union?',27,'Staaten'),
    (uid,'In welchem Jahr fiel die Berliner Mauer?',1989,''),
    (uid,'Wie hoch ist die Zugspitze?',2962,'m'),
    (uid,'Wie viele Tasten hat ein Klavier?',88,'Tasten'),
    (uid,'Wie viele Minuten hat ein Tag?',1440,'Minuten'),
    (uid,'Wie viele Bundesländer hat Deutschland?',16,'Bundesländer'),
    (uid,'Wie schnell ist Schall in Luft bei 20 °C?',343,'m/s'),
    (uid,'Wie lang ist ein Marathon?',42.195,'km');
  end if;
 end if;
 if p_action='question_list' then
  return jsonb_build_object('ok',true,'questions',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'question',question,'answer',answer,'unit',unit) order by id),'[]') from private.closer_questions where owner_id=uid));
 elsif p_action='question_save' then
  txt:=btrim(a->>'p_question');qid:=(a->>'p_id')::bigint;v_unit:=btrim(coalesce(a->>'p_unit',''));
  if txt is null or length(txt) not between 5 and 300 then return jsonb_build_object('ok',false,'error','INVALID_QUESTION');end if;
  if a->>'p_answer' is null or (a->>'p_answer')!~'^-?[0-9]+(\.[0-9]+)?$' then return jsonb_build_object('ok',false,'error','INVALID_ANSWER');end if;
  num:=(a->>'p_answer')::numeric;
  if abs(num)>1000000000000 then return jsonb_build_object('ok',false,'error','INVALID_ANSWER');end if;
  if length(v_unit)>20 then return jsonb_build_object('ok',false,'error','INVALID_UNIT');end if;
  if qid is null then insert into private.closer_questions(owner_id,question,answer,unit) values(uid,txt,num,v_unit) returning id into qid;
  else update private.closer_questions set question=txt,answer=num,unit=v_unit where id=qid and owner_id=uid;
   if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
  end if;
  return jsonb_build_object('ok',true,'id',qid);
 elsif p_action='question_delete' then
  delete from private.closer_questions where id=(a->>'p_id')::bigint and owner_id=uid;
  if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 elsif p_action='quiz_list' then
  return jsonb_build_object('ok',true,'quizzes',(select coalesce(jsonb_agg(to_jsonb(q) order by q.name),'[]') from (select id,name,questions from private.closer_quizzes where owner_id=uid) q));
 elsif p_action='quiz_delete' then
  delete from private.closer_quizzes where id=(a->>'p_id')::uuid and owner_id=uid;
  if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 elsif p_action in ('quiz_save','create','quiz_start') then
  if p_action='quiz_start' then
   select questions into qs from private.closer_quizzes where id=(a->>'p_id')::uuid and owner_id=uid;
   if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
  else
   select array_agg(x::bigint) into ids from jsonb_array_elements_text(nullif(a->'p_question_ids','null')) x;
   n:=case when p_action='quiz_save' then cardinality(ids) else (a->>'p_round_count')::integer end;
   if n is null or n not between 1 and 50 then return jsonb_build_object('ok',false,'error','INVALID_ROUND_COUNT');end if;
   if ids is not null then
    -- Saved games keep copies, so removed bank questions stay selectable when editing that game.
    if cardinality(ids)<>n or (select count(distinct x) from unnest(ids) x)<>n or exists(select 1 from unnest(ids) x where not exists(select 1 from private.closer_questions where id=x and owner_id=uid) and not (p_action='quiz_save' and exists(select 1 from private.closer_quizzes q cross join lateral jsonb_array_elements(q.questions) v where q.id=(a->>'p_id')::uuid and q.owner_id=uid and (v->>'id')::bigint=x))) then
     return jsonb_build_object('ok',false,'error','INVALID_SELECTION');end if;
    select jsonb_agg(coalesce((select jsonb_build_object('id',id,'question',question,'answer',answer,'unit',unit) from private.closer_questions where id=x and owner_id=uid),(select v from private.closer_quizzes q cross join lateral jsonb_array_elements(q.questions) v where q.id=(a->>'p_id')::uuid and q.owner_id=uid and (v->>'id')::bigint=x)) order by ord) into qs from unnest(ids) with ordinality t(x,ord);
   else
    select jsonb_agg(jsonb_build_object('id',id,'question',question,'answer',answer,'unit',unit)) into qs from (select * from private.closer_questions where owner_id=uid order by random() limit n) q;
    if coalesce(jsonb_array_length(qs),0)<>n then return jsonb_build_object('ok',false,'error','NOT_ENOUGH_QUESTIONS');end if;
   end if;
  end if;
  if p_action='quiz_save' then
   txt:=btrim(a->>'p_name');sid:=(a->>'p_id')::uuid;
   if txt is null or length(txt) not between 1 and 120 then return jsonb_build_object('ok',false,'error','INVALID_NAME');end if;
   if sid is null then insert into private.closer_quizzes(owner_id,name,questions) values(uid,txt,qs);
   else update private.closer_quizzes set name=txt,questions=qs where id=sid and owner_id=uid;
    if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
   end if;
  else
   loop
    code:=upper(substr(replace(gen_random_uuid()::text,'-',''),1,5));
    exit when not exists(select 1 from private.closer_sessions where join_code=code);
   end loop;
   insert into private.closer_sessions(owner_id,join_code,questions) values(uid,code,qs) returning id into sid;
   insert into public.closer_live_signals values(sid,1);
   return jsonb_build_object('ok',true,'session_id',sid,'join_code',code);
  end if;
 elsif p_action in ('join','host_state','player_state','host_action','guess') then
  if p_action='join' then
   if not private.classroom_join_allowed('closer') then return jsonb_build_object('ok',false,'error','JOIN_RATE_LIMITED');end if;
   select * into s from private.closer_sessions where join_code=upper(btrim(a->>'p_code')) for update;
  else select * into s from private.closer_sessions where id=(a->>'p_session_id')::uuid for update;end if;
  if not found then return jsonb_build_object('ok',false,'error','SESSION_NOT_FOUND');end if;
  if p_action in ('host_state','host_action') then
   if s.owner_id is distinct from uid then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
  else
   if coalesce(a->>'p_token','') !~ '^[a-f0-9]{64}$' then return jsonb_build_object('ok',false,'error','INVALID_PARTICIPANT_TOKEN');end if;
   if p_action='join' then
    select * into p from private.closer_players where session_id=s.id and token_hash=encode(sha256(convert_to(a->>'p_token','UTF8')),'hex');
    if not found then
     if s.phase<>'lobby' then return jsonb_build_object('ok',false,'error','GAME_ALREADY_STARTED');end if;
     txt:=btrim(a->>'p_name');
     if txt is null or length(txt) not between 1 and 40 then return jsonb_build_object('ok',false,'error','INVALID_JOIN_INPUT');end if;
     if (select count(*) from private.closer_players where session_id=s.id)>=50 then return jsonb_build_object('ok',false,'error','ROOM_FULL');end if;
     if exists(select 1 from private.closer_players where session_id=s.id and lower(btrim(name))=lower(txt)) then return jsonb_build_object('ok',false,'error','NAME_TAKEN');end if;
     insert into private.closer_players(session_id,name,token_hash) values(s.id,txt,encode(sha256(convert_to(a->>'p_token','UTF8')),'hex')) returning * into p;
     changed:=true;
    end if;
   else
    select * into p from private.closer_players where id=(a->>'p_player_id')::uuid and session_id=s.id and token_hash=encode(sha256(convert_to(a->>'p_token','UTF8')),'hex');
    if not found then return jsonb_build_object('ok',false,'error','INVALID_PARTICIPANT_TOKEN');end if;
   end if;
   pid:=p.id;
  end if;
  if p_action='guess' then
   if s.phase<>'guess' or (a->>'p_round')::integer is distinct from s.round_index then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
   if a->>'p_value' is null or (a->>'p_value')!~'^-?[0-9]+(\.[0-9]+)?$' then return jsonb_build_object('ok',false,'error','INVALID_GUESS');end if;
   num:=(a->>'p_value')::numeric;
   if abs(num)>1000000000000 then return jsonb_build_object('ok',false,'error','INVALID_GUESS');end if;
   -- A guess can be corrected until the host reveals the answer.
   insert into private.closer_guesses(session_id,round_index,player_id,value) values(s.id,s.round_index,pid,num)
    on conflict(session_id,round_index,player_id) do update set value=excluded.value where private.closer_guesses.value is distinct from excluded.value;
   changed:=true;
  elsif p_action='host_action' then
   txt:=a->>'p_action';
   if txt='end' then
    if s.phase<>'ended' then update private.closer_sessions set phase='ended' where id=s.id;changed:=true;end if;
   else
    if (a->>'p_round')::integer is distinct from s.round_index or a->>'p_phase' is distinct from s.phase then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
    if txt='start' and s.phase='lobby' then
     if (select count(*) from private.closer_players where session_id=s.id)<2 then return jsonb_build_object('ok',false,'error','NEED_TWO_PLAYERS');end if;
     update private.closer_sessions set phase='guess' where id=s.id;
    elsif txt='reveal' and s.phase='guess' then
     if not exists(select 1 from private.closer_guesses where session_id=s.id and round_index=s.round_index) then return jsonb_build_object('ok',false,'error','NO_GUESSES');end if;
     -- Closest guess 3 points, second 2, third 1. Equal distances share a place and its points.
     v_answer:=(s.questions->s.round_index->>'answer')::numeric;
     update private.closer_guesses g set points=case r.place when 1 then 3 when 2 then 2 when 3 then 1 else 0 end
      from (select player_id,1+(select count(*) from private.closer_guesses o where o.session_id=s.id and o.round_index=s.round_index and abs(o.value-v_answer)<abs(x.value-v_answer)) place
            from private.closer_guesses x where x.session_id=s.id and x.round_index=s.round_index) r
      where g.session_id=s.id and g.round_index=s.round_index and g.player_id=r.player_id;
     update private.closer_players pl set score=pl.score+g.points from private.closer_guesses g
      where g.session_id=s.id and g.round_index=s.round_index and g.player_id=pl.id and pl.session_id=s.id;
     update private.closer_sessions set phase='reveal' where id=s.id;
    elsif txt='scores' and s.phase='reveal' then update private.closer_sessions set phase='leaderboard' where id=s.id;
    elsif txt='next' and s.phase in ('reveal','leaderboard') then
     update private.closer_sessions set phase=case when round_index+1=jsonb_array_length(questions) then 'ended' else 'guess' end,
      round_index=least(round_index+1,jsonb_array_length(questions)-1) where id=s.id;
    else return jsonb_build_object('ok',false,'error','INVALID_ACTION');end if;
    changed:=true;
   end if;
  end if;
  if changed then
   update private.closer_sessions set revision=revision+1 where id=s.id returning * into s;
   update public.closer_live_signals set revision=s.revision where session_id=s.id;
  end if;
  if p_action='join' then return jsonb_build_object('ok',true,'session_id',s.id,'player_id',pid,'name',p.name,'join_code',s.join_code);end if;
  if p_action in ('host_state','player_state') then
   v_answer:=case when s.phase in ('reveal','leaderboard') then (s.questions->s.round_index->>'answer')::numeric end;
   return jsonb_build_object('ok',true,'session_id',s.id,'join_code',s.join_code,'revision',s.revision,'phase',s.phase,'round_index',s.round_index,'round_count',jsonb_array_length(s.questions),
    'question',case when s.phase not in ('lobby','ended') then s.questions->s.round_index->>'question' end,
    'unit',case when s.phase not in ('lobby','ended') then coalesce(s.questions->s.round_index->>'unit','') end,
    'answer',v_answer,
    'own_guess',(select value from private.closer_guesses where session_id=s.id and round_index=s.round_index and player_id=pid),
    'players',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'name',name,'score',score,'guessed',exists(select 1 from private.closer_guesses where session_id=s.id and round_index=s.round_index and player_id=pl.id)) order by score desc,joined_at,id),'[]') from private.closer_players pl where session_id=s.id),
    -- Guesses stay hidden from everybody until the reveal.
    'results',case when v_answer is not null then (select coalesce(jsonb_agg(jsonb_build_object('id',pl.id,'name',pl.name,'value',g.value,'distance',abs(g.value-v_answer),'points',coalesce(g.points,0)) order by abs(g.value-v_answer),pl.joined_at,pl.id),'[]') from private.closer_guesses g join private.closer_players pl on pl.id=g.player_id where g.session_id=s.id and g.round_index=s.round_index) else '[]'::jsonb end);
  end if;
 else return jsonb_build_object('ok',false,'error','INVALID_ACTION');
 end if;
 return jsonb_build_object('ok',true);
end;$$;

