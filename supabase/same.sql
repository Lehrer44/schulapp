-- Das gleiche Antworten. Apply after rather.sql. Private storage and checked APIs.
create table if not exists private.same_catalogs(owner_id uuid primary key references auth.users on delete cascade);
create table if not exists private.same_questions(
 id bigint generated by default as identity primary key,owner_id uuid not null references auth.users on delete cascade,
 kind text not null default 'association' check(kind in ('association','team')),
 question text not null check(length(btrim(question)) between 5 and 500)
);
create index if not exists same_questions_owner on private.same_questions(owner_id);
create table if not exists private.same_quizzes(
 id uuid primary key default gen_random_uuid(),owner_id uuid not null references auth.users on delete cascade,
 name text not null check(length(btrim(name)) between 1 and 120),questions jsonb not null
);
create index if not exists same_quizzes_owner on private.same_quizzes(owner_id);
create table if not exists private.same_sessions(
 id uuid primary key default gen_random_uuid(),owner_id uuid not null references auth.users on delete cascade,
 join_code text unique not null,questions jsonb not null,round_index integer not null default 0,
 phase text not null default 'lobby' check(phase in ('lobby','answers','reveal','leaderboard','ended')),
 team_count integer not null default 2 check(team_count between 2 and 10),
 timer_seconds integer not null default 0 check(timer_seconds between 0 and 600),deadline timestamptz,
 revision bigint not null default 1,created_at timestamptz not null default now()
);
create index if not exists same_sessions_owner on private.same_sessions(owner_id);
create table if not exists private.same_players(
 id uuid primary key default gen_random_uuid(),session_id uuid not null references private.same_sessions on delete cascade,
 name text not null check(length(btrim(name)) between 1 and 40),token_hash text not null,team integer check(team between 1 and 10),
 joined_at timestamptz not null default clock_timestamp(),unique(session_id,id)
);
create unique index if not exists same_player_name on private.same_players(session_id,lower(btrim(name)));
create table if not exists private.same_answers(
 session_id uuid not null,round_index integer not null,player_id uuid not null,
 answer text not null check(length(btrim(answer)) between 1 and 180),revealed boolean not null default false,
 primary key(session_id,round_index,player_id),
 foreign key(session_id,player_id) references private.same_players(session_id,id) on delete cascade
);
create table if not exists private.same_points(
 session_id uuid not null references private.same_sessions on delete cascade,round_index integer not null,
 team integer not null,points integer not null check(points between 0 and 3),primary key(session_id,round_index,team)
);
create table if not exists public.same_live_signals(
 session_id uuid primary key references private.same_sessions on delete cascade,revision bigint not null
);
alter table public.same_live_signals enable row level security;
drop policy if exists same_signal_read on public.same_live_signals;
create policy same_signal_read on public.same_live_signals for select to anon,authenticated using(true);
revoke all on public.same_live_signals from public,anon,authenticated;
grant select on public.same_live_signals to anon,authenticated;
do $$declare t text;begin
 foreach t in array array['catalogs','questions','quizzes','sessions','players','answers','points'] loop
 execute format('alter table private.%I enable row level security','same_'||t);
 execute format('revoke all on private.%I from public,anon,authenticated','same_'||t);
 end loop;
 if exists(select 1 from pg_publication where pubname='supabase_realtime') and not exists(select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='same_live_signals') then
 alter publication supabase_realtime add table public.same_live_signals;
 end if;
end;$$;

-- One private implementation keeps authentication, locking and visibility rules together.
-- It is reachable only via the narrow public invoker wrappers below.
create or replace function private.same_api(p_action text,a jsonb)
returns jsonb language plpgsql security definer set search_path='' as $$
declare uid uuid:=auth.uid();s private.same_sessions%rowtype;p private.same_players%rowtype;
 sid uuid;pid uuid;qid bigint;qs jsonb;ids bigint[];code text;txt text;j jsonb;target uuid;team_no integer;pts integer;
 n integer;changed boolean:=false;
begin
 if p_action not in ('join','player_state','answer') and uid is null then return jsonb_build_object('ok',false,'error','NOT_AUTHENTICATED');end if;
 if p_action in ('question_list','question_save','question_delete','quiz_list','quiz_save','quiz_delete','quiz_start','create') then
  -- Seed once per account, so editing/deleting a starter never affects another teacher.
  insert into private.same_catalogs values(uid) on conflict do nothing;
  if found then
   insert into private.same_questions(owner_id,question) select uid,x from unnest(array[
    'Nenne ein Obst außer Apfel oder Banane.','Nenne etwas Teures.','Nenne eine Fastfood-Kette.',
    'Nenne ein Möbelstück.','Nenne eine Cartoonserie.','Nenne ein Tier im Zoo.',
    'Wer von euch ist am sportlichsten?','Wer geht am frühesten schlafen?',
    'Wer landet am ehesten im Gefängnis?','Wer von euch lacht am meisten?']) x;
   update private.same_questions set kind='team' where owner_id=uid and question like 'Wer%';
  end if;
 end if;
 if p_action='question_list' then
  return jsonb_build_object('ok',true,'questions',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'question',question,'kind',kind) order by id),'[]') from private.same_questions where owner_id=uid));
 elsif p_action='question_save' then
  if coalesce(a->>'p_kind','') not in ('association','team') then return jsonb_build_object('ok',false,'error','INVALID_KIND');end if;
  txt:=btrim(a->>'p_question');qid:=(a->>'p_id')::bigint;
  if txt is null or length(txt) not between 5 and 500 then return jsonb_build_object('ok',false,'error','INVALID_QUESTION');end if;
  if qid is null then insert into private.same_questions(owner_id,question,kind) values(uid,txt,a->>'p_kind') returning id into qid;
  else update private.same_questions set question=txt,kind=a->>'p_kind' where id=qid and owner_id=uid;
   if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
  end if;
  return jsonb_build_object('ok',true,'id',qid);
 elsif p_action='question_delete' then
  delete from private.same_questions where id=(a->>'p_id')::bigint and owner_id=uid;
  if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 elsif p_action='quiz_list' then
  return jsonb_build_object('ok',true,'quizzes',(select coalesce(jsonb_agg(to_jsonb(q) order by q.name),'[]') from (select id,name,questions from private.same_quizzes where owner_id=uid) q));
 elsif p_action='quiz_delete' then
  delete from private.same_quizzes where id=(a->>'p_id')::uuid and owner_id=uid;
  if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
 elsif p_action in ('quiz_save','create','quiz_start') then
  if p_action='quiz_start' then
   select questions into qs from private.same_quizzes where id=(a->>'p_id')::uuid and owner_id=uid;
   if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
  else
   select array_agg(x::bigint) into ids from jsonb_array_elements_text(nullif(a->'p_question_ids','null')) x;
   n:=case when p_action='quiz_save' then cardinality(ids) else (a->>'p_round_count')::integer end;
   if n is null or n not between 1 and 50 then return jsonb_build_object('ok',false,'error','INVALID_ROUND_COUNT');end if;
   if ids is not null then
    if cardinality(ids)<>n or (select count(distinct x) from unnest(ids) x)<>n or exists(select 1 from unnest(ids) x where not exists(select 1 from private.same_questions where id=x and owner_id=uid) and not (p_action='quiz_save' and exists(select 1 from private.same_quizzes q cross join lateral jsonb_array_elements(q.questions) v where q.id=(a->>'p_id')::uuid and q.owner_id=uid and (v->>'id')::bigint=x))) then
     return jsonb_build_object('ok',false,'error','INVALID_SELECTION');end if;
    select jsonb_agg(coalesce((select jsonb_build_object('id',id,'question',question,'kind',kind) from private.same_questions where id=x and owner_id=uid),(select v from private.same_quizzes q cross join lateral jsonb_array_elements(q.questions) v where q.id=(a->>'p_id')::uuid and q.owner_id=uid and (v->>'id')::bigint=x)) order by ord) into qs from unnest(ids) with ordinality t(x,ord);
   else
    select jsonb_agg(jsonb_build_object('id',id,'question',question,'kind',kind)) into qs from (select * from private.same_questions where owner_id=uid order by random() limit n) q;
    if coalesce(jsonb_array_length(qs),0)<>n then return jsonb_build_object('ok',false,'error','NOT_ENOUGH_QUESTIONS');end if;
   end if;
  end if;
  if p_action='quiz_save' then
   txt:=btrim(a->>'p_name');sid:=(a->>'p_id')::uuid;
   if txt is null or length(txt) not between 1 and 120 then return jsonb_build_object('ok',false,'error','INVALID_NAME');end if;
   if sid is null then insert into private.same_quizzes(owner_id,name,questions) values(uid,txt,qs);
   else update private.same_quizzes set name=txt,questions=qs where id=sid and owner_id=uid;
    if not found then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
   end if;
  else
   loop
    code:=upper(substr(replace(gen_random_uuid()::text,'-',''),1,5));
    exit when not exists(select 1 from private.same_sessions where join_code=code);
   end loop;
   insert into private.same_sessions(owner_id,join_code,questions) values(uid,code,qs) returning id into sid;
   insert into public.same_live_signals values(sid,1);
   return jsonb_build_object('ok',true,'session_id',sid,'join_code',code);
  end if;
 elsif p_action in ('join','host_state','player_state','host_action','answer','manage') then
  if p_action='join' then
   if not private.classroom_join_allowed('same') then return jsonb_build_object('ok',false,'error','JOIN_RATE_LIMITED');end if;
   select * into s from private.same_sessions where join_code=upper(btrim(a->>'p_code')) for update;
  else select * into s from private.same_sessions where id=(a->>'p_session_id')::uuid for update;end if;
  if not found then return jsonb_build_object('ok',false,'error','SESSION_NOT_FOUND');end if;
  if p_action in ('host_state','host_action','manage') then
   if s.owner_id is distinct from uid then return jsonb_build_object('ok',false,'error','NOT_OWNER');end if;
  else
   if coalesce(a->>'p_token','') !~ '^[a-f0-9]{64}$' then return jsonb_build_object('ok',false,'error','INVALID_PARTICIPANT_TOKEN');end if;
   if p_action='join' then
    select * into p from private.same_players where session_id=s.id and token_hash=encode(sha256(convert_to(a->>'p_token','UTF8')),'hex');
    if not found then
     if s.phase<>'lobby' then return jsonb_build_object('ok',false,'error','GAME_ALREADY_STARTED');end if;
     txt:=btrim(a->>'p_name');
     if txt is null or length(txt) not between 1 and 40 then return jsonb_build_object('ok',false,'error','INVALID_JOIN_INPUT');end if;
     if (select count(*) from private.same_players where session_id=s.id)>=50 then return jsonb_build_object('ok',false,'error','ROOM_FULL');end if;
     if exists(select 1 from private.same_players where session_id=s.id and lower(name)=lower(txt)) then return jsonb_build_object('ok',false,'error','NAME_TAKEN');end if;
     insert into private.same_players(session_id,name,token_hash) values(s.id,txt,encode(sha256(convert_to(a->>'p_token','UTF8')),'hex')) returning * into p;
     changed:=true;
    end if;
   else
    select * into p from private.same_players where id=(a->>'p_player_id')::uuid and session_id=s.id and token_hash=encode(sha256(convert_to(a->>'p_token','UTF8')),'hex');
    if not found then return jsonb_build_object('ok',false,'error','INVALID_PARTICIPANT_TOKEN');end if;
   end if;
   pid:=p.id;
  end if;
  -- A session row lock serializes submissions, timer expiry, scoring and overrides.
  if s.phase='answers' and s.deadline is not null and clock_timestamp()>=s.deadline then
   update private.same_sessions set phase='reveal',deadline=null,revision=revision+1 where id=s.id returning * into s;
   update public.same_live_signals set revision=s.revision where session_id=s.id;
  end if;
  if p_action='answer' then
   if s.phase<>'answers' or (a->>'p_round')::integer is distinct from s.round_index then
    if changed then
     update private.same_sessions set revision=revision+1 where id=s.id returning * into s;
     update public.same_live_signals set revision=s.revision where session_id=s.id;
    end if;
    return jsonb_build_object('ok',false,'error','PHASE_CHANGED');
   end if;
   txt:=regexp_replace(a->>'p_answer','^[[:space:]]+|[[:space:]]+$','','g');
   if txt is null or length(txt) not between 1 and 180 then return jsonb_build_object('ok',false,'error','INVALID_ANSWER');end if;
   if s.questions->s.round_index->>'kind'='team' and not exists(
    select 1 from private.same_players where session_id=s.id and team=p.team and lower(name)=lower(txt)
   ) then return jsonb_build_object('ok',false,'error','TEAM_NAME_REQUIRED');end if;
   if exists(select 1 from private.same_answers where session_id=s.id and round_index=s.round_index and player_id=pid) then
    if not exists(select 1 from private.same_answers where session_id=s.id and round_index=s.round_index and player_id=pid and answer=txt) then return jsonb_build_object('ok',false,'error','ANSWER_ALREADY_CAST');end if;
   else
    insert into private.same_answers(session_id,round_index,player_id,answer) values(s.id,s.round_index,pid,txt);changed:=true;
   end if;
   if (select count(*) from private.same_answers where session_id=s.id and round_index=s.round_index)=(select count(*) from private.same_players where session_id=s.id) then
    update private.same_sessions set phase='reveal',deadline=null where id=s.id;
   end if;
  elsif p_action='manage' then
   if (a->>'p_round')::integer is distinct from s.round_index or a->>'p_phase' is distinct from s.phase then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
   txt:=a->>'p_action';target:=(a->>'p_target')::uuid;team_no:=(a->>'p_team')::integer;
   if txt='configure' and s.phase='lobby' then
    n:=(a->>'p_value')::integer;
    if team_no is null or team_no not between 2 and 10 or n is null or n not between 0 and 600 then return jsonb_build_object('ok',false,'error','INVALID_SETTINGS');end if;
    update private.same_sessions set team_count=team_no,timer_seconds=n where id=s.id;
    update private.same_players set team=null where session_id=s.id and team>team_no;
   elsif txt='assign' and s.phase='lobby' then
    if team_no is null or team_no not between 1 and s.team_count then return jsonb_build_object('ok',false,'error','INVALID_TEAM');end if;
    update private.same_players set team=team_no where session_id=s.id and id=target;
    if not found then return jsonb_build_object('ok',false,'error','INVALID_PLAYER');end if;
   elsif txt='reveal' and s.phase='reveal' then
    update private.same_answers set revealed=true where session_id=s.id and round_index=s.round_index and player_id=target;
   elsif txt='correct' and s.phase='reveal' then
    j:=a->'p_value';txt:=regexp_replace(j#>>'{}','^[[:space:]]+|[[:space:]]+$','','g');
    if txt is null or length(txt) not between 1 and 180 then return jsonb_build_object('ok',false,'error','INVALID_ANSWER');end if;
    update private.same_answers set answer=txt where session_id=s.id and round_index=s.round_index and player_id=target and revealed;
    if not found then return jsonb_build_object('ok',false,'error','INVALID_ACTION');end if;
    if s.questions->s.round_index->>'kind'='team' and not exists(select 1 from private.same_players pl join private.same_players chosen on chosen.session_id=pl.session_id and chosen.team=pl.team where pl.id=target and pl.session_id=s.id and lower(chosen.name)=lower(txt)) then
     raise exception 'TEAM_NAME_REQUIRED';
    end if;
   elsif txt='override' and s.phase='leaderboard' then
    pts:=(a->>'p_value')::integer;
    if pts is null or pts not between 0 and 3 or team_no is null or team_no not between 1 and s.team_count then return jsonb_build_object('ok',false,'error','INVALID_POINTS');end if;
    update private.same_points set points=pts where session_id=s.id and round_index=s.round_index and team=team_no;
   else return jsonb_build_object('ok',false,'error','INVALID_ACTION');end if;
   changed:=true;
  elsif p_action='host_action' then
   txt:=a->>'p_action';
   if txt='end' then
    if s.phase<>'ended' then update private.same_sessions set phase='ended',deadline=null where id=s.id;changed:=true;end if;
   else
    if (a->>'p_round')::integer is distinct from s.round_index or a->>'p_phase' is distinct from s.phase then return jsonb_build_object('ok',false,'error','PHASE_CHANGED');end if;
    if txt='start' and s.phase='lobby' then
     select count(*) into n from private.same_players where session_id=s.id;
     if n<s.team_count*2 or n%s.team_count<>0 or exists(select 1 from private.same_players where session_id=s.id and team is null) or exists(select 1 from generate_series(1,s.team_count) t where (select count(*) from private.same_players where session_id=s.id and team=t)<>n/s.team_count) then
      return jsonb_build_object('ok',false,'error','TEAMS_NOT_BALANCED');end if;
     update private.same_sessions set phase='answers',deadline=case when timer_seconds>0 then clock_timestamp()+timer_seconds*interval '1 second' end where id=s.id;
    elsif txt='close' and s.phase='answers' then update private.same_sessions set phase='reveal',deadline=null where id=s.id;
    elsif txt='scores' and s.phase='reveal' then
     if exists(select 1 from private.same_answers where session_id=s.id and round_index=s.round_index and not revealed) then return jsonb_build_object('ok',false,'error','REVEAL_FIRST');end if;
     insert into private.same_points(session_id,round_index,team,points)
      select s.id,s.round_index,t,
       case when (select count(*) from private.same_answers an join private.same_players pl on pl.id=an.player_id where an.session_id=s.id and an.round_index=s.round_index and pl.team=t)=(select count(*) from private.same_players where session_id=s.id and team=t)
        and (select count(distinct lower(btrim(an.answer))) from private.same_answers an join private.same_players pl on pl.id=an.player_id where an.session_id=s.id and an.round_index=s.round_index and pl.team=t)=1 then 3
       when exists(select 1 from private.same_answers an join private.same_players pl on pl.id=an.player_id where an.session_id=s.id and an.round_index=s.round_index and pl.team=t group by lower(btrim(an.answer)) having count(*)>=2) then 1 else 0 end
      from generate_series(1,s.team_count) t;
     update private.same_sessions set phase='leaderboard' where id=s.id;
    elsif txt='next' and s.phase='leaderboard' then
     update private.same_sessions set phase=case when round_index+1=jsonb_array_length(questions) then 'ended' else 'answers' end,
      deadline=case when round_index+1<jsonb_array_length(questions) and timer_seconds>0 then clock_timestamp()+timer_seconds*interval '1 second' end,
      round_index=least(round_index+1,jsonb_array_length(questions)-1) where id=s.id;
    else return jsonb_build_object('ok',false,'error','INVALID_ACTION');end if;
    changed:=true;
   end if;
  end if;
  if changed then
   update private.same_sessions set revision=revision+1 where id=s.id returning * into s;
   update public.same_live_signals set revision=s.revision where session_id=s.id;
  end if;
  if p_action='join' then return jsonb_build_object('ok',true,'session_id',s.id,'player_id',pid,'name',p.name,'join_code',s.join_code);end if;
  if p_action in ('host_state','player_state') then
   return jsonb_build_object('ok',true,'session_id',s.id,'join_code',s.join_code,'revision',s.revision,'phase',s.phase,'round_index',s.round_index,'round_count',jsonb_array_length(s.questions),
    'question',case when s.phase not in ('lobby','ended') then s.questions->s.round_index->>'question' end,
    'kind',s.questions->s.round_index->>'kind','team_count',s.team_count,'timer_seconds',s.timer_seconds,'deadline',s.deadline,
    'own_answer',(select answer from private.same_answers where session_id=s.id and round_index=s.round_index and player_id=pid),
    'teams',(select jsonb_agg(jsonb_build_object('id',t,'score',coalesce((select sum(points) from private.same_points where session_id=s.id and team=t),0),'round_points',(select points from private.same_points where session_id=s.id and round_index=s.round_index and team=t)) order by t) from generate_series(1,s.team_count) t),
    'players',(select coalesce(jsonb_agg(jsonb_build_object('id',pl.id,'name',pl.name,'team',pl.team,'submitted',an.player_id is not null,'revealed',coalesce(an.revealed,false)) ||
     case when an.revealed and s.phase in ('reveal','leaderboard','ended') then jsonb_build_object('answer',an.answer) else '{}'::jsonb end order by pl.joined_at,pl.id),'[]')
     from private.same_players pl left join private.same_answers an on an.session_id=pl.session_id and an.player_id=pl.id and an.round_index=s.round_index where pl.session_id=s.id));
  end if;
 else return jsonb_build_object('ok',false,'error','INVALID_ACTION');
 end if;
 return jsonb_build_object('ok',true);
end;$$;
-- No extension-specific random byte function is needed for short public room codes.

-- Public APIs never elevate privileges. The private dispatcher validates every action.
grant usage on schema private to anon,authenticated;
revoke all on function private.same_api(text,jsonb) from public,anon,authenticated;
grant execute on function private.same_api(text,jsonb) to anon,authenticated;

create or replace function public.same_question_list() returns jsonb language sql security invoker set search_path='' as $$select private.same_api('question_list',jsonb_build_object());$$;
revoke all on function public.same_question_list() from public,anon,authenticated;
grant execute on function public.same_question_list() to authenticated;

create or replace function public.same_question_save(p_id bigint,p_question text,p_kind text) returns jsonb language sql security invoker set search_path='' as $$select private.same_api('question_save',jsonb_build_object('p_id',p_id,'p_question',p_question,'p_kind',p_kind));$$;
revoke all on function public.same_question_save(bigint,text,text) from public,anon,authenticated;
grant execute on function public.same_question_save(bigint,text,text) to authenticated;

create or replace function public.same_question_delete(p_id bigint) returns jsonb language sql security invoker set search_path='' as $$select private.same_api('question_delete',jsonb_build_object('p_id',p_id));$$;
